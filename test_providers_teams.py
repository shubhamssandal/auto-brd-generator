def test_discovery_walks_calendar_events_to_transcripts(provider, monkeypatch):
    calls = []

    def fake_get(url, *args, **kwargs):
        calls.append((url, dict(kwargs.get("params") or {})))
        if "/transcripts" in url:
            return FakeResponse({"value": [
                {"id": "transcript-1", "createdDateTime": "2026-08-20T10:05:00Z",
                 "endDateTime": "2026-08-20T10:00:00Z"}
            ]})
        if "/onlineMeetings" in url:
            return FakeResponse({"value": [{"id": "meeting-1", "joinWebUrl": JOIN_URL}]})
        return events_response()

    monkeypatch.setattr(requests, "get", fake_get)

    result = provider.discover_transcripts(access_token="at-1")
    entries = result["transcripts"]

    assert len(entries) == 1
    entry = entries[0]
    assert entry["id"] == "meeting-1/transcripts/transcript-1"
    # Title and date come from the real calendar event / transcript resource.
    assert entry["title"] == "Refund Dashboard Review"
    assert entry["date"] == "2026-08-20T10:05:00Z"
    assert entry["source_type"] == "ms_graph_transcript"
    assert entry["available"] is True
    assert entry["details"]["organizer"] == "Sarah Khan"
    assert "Priya Nair" in entry["participants"]

    events_call = next(c for c in calls if c[0].endswith("/me/events"))
    params = events_call[1]
    assert params["$filter"] == "isOnlineMeeting eq true"
    # Graph rejects some filter+sort combinations on /me/events, so ordering is
    # done client-side rather than with $orderby.
    assert "$orderby" not in params
    assert "onlineMeeting" in params["$select"]


