def test_get_transcript_requests_vtt_and_normalizes_it(provider, monkeypatch):
    requested = []

    def fake_get(url, *args, **kwargs):
        requested.append((url, dict(kwargs.get("params") or {}), dict(kwargs.get("headers") or {})))
        if url.endswith("/content"):
            return FakeResponse(status_code=200, text=VTT_SAMPLE,
                                headers={"Content-Type": "text/vtt"})
        return FakeResponse({"id": "transcript-1", "createdDateTime": "2026-08-20T10:05:00Z"})

    monkeypatch.setattr(requests, "get", fake_get)

    transcript = provider.get_transcript(
        "meeting-1/transcripts/transcript-1",
        access_token="at-1",
        meeting_title="Refund Dashboard Review",
    )

    assert transcript.source == "microsoft_teams"
    assert transcript.provider == "microsoft_teams"
    assert transcript.transcript_id == "meeting-1/transcripts/transcript-1"
    assert transcript.metadata["transcript_id"] == "transcript-1"
    assert transcript.meeting_title == "Refund Dashboard Review"
    assert transcript.meeting_date == "2026-08-20T10:05:00Z"
    assert transcript.participants == ["Sarah Khan", "Priya"]
    assert transcript.metadata["content_format"] == "text/vtt"
    assert transcript.metadata["speaker_attributed"] is True
    assert transcript.metadata["online_meeting_id"] == "meeting-1"
    assert transcript.metadata["meeting_resource"] == "meeting-1/transcripts/transcript-1"

    content_call = next(c for c in requested if c[0].endswith("/content"))
    assert content_call[1].get("$format") == "text/vtt"
    assert content_call[2].get("Accept") == "text/vtt"


