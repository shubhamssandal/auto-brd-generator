def test_speaker_attribution_denied_falls_back_to_unattributed_text(provider, monkeypatch):
    """SpeakerAttributionNotAllowed only affects VTT; the plain type must be retried."""
    attempts = []

    def fake_get(url, *args, **kwargs):
        headers = dict(kwargs.get("headers") or {})
        if url.endswith("/content"):
            attempts.append(headers.get("Accept"))
            if headers.get("Accept") == "text/vtt":
                return FakeResponse(
                    {"error": {"code": "Forbidden",
                               "message": "Speaker attribution is not allowed.",
                               "innerError": {"code": "SpeakerAttributionNotAllowed"}}},
                    status_code=403,
                )
            return FakeResponse(
                status_code=200,
                text="Support volume is up 30% this quarter.\nWe need email notifications.",
                headers={"Content-Type": "text/plain"},
            )
        return FakeResponse({"id": "transcript-1"})

    monkeypatch.setattr(requests, "get", fake_get)

    transcript = provider.get_transcript("meeting-1/transcripts/transcript-1", access_token="at-1")

    assert attempts == ["text/vtt", "application/vnd.microsoft.graph.transcript+text"]
    assert transcript.metadata["speaker_attributed"] is False
    assert transcript.metadata["content_format"] == "text/plain"
    assert transcript.participants == []
    assert "speaker_attribution_note" in transcript.metadata
    # The wording must survive verbatim so evidence validation can still match it.
    assert "Support volume is up 30% this quarter." in transcript.raw_text


