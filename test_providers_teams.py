class FakeResponse:
    def __init__(self, body=None, status_code=200, text="", headers=None):
        self.status_code = status_code
        self._body = body
        self.text = text
        self.headers = headers or {}

    def json(self):
        if self._body is None:
            raise ValueError("no JSON body")
        return self._body


def events_response(subject="Refund Dashboard Review", join_url=JOIN_URL, include_online_meeting=True):
    event = {
        "id": "event-1",
        "subject": subject,
        "isOnlineMeeting": True,
        "start": {"dateTime": "2026-08-20T09:00:00.0000000", "timeZone": "UTC"},
        "end": {"dateTime": "2026-08-20T10:00:00.0000000", "timeZone": "UTC"},
        "organizer": {"emailAddress": {"name": "Sarah Khan", "address": "sarah@example.com"}},
        "attendees": [
            {"emailAddress": {"name": "Priya Nair", "address": "priya@example.com"}},
            {"emailAddress": {"name": "Rahul Mehta", "address": "rahul@example.com"}},
        ],
    }
    if include_online_meeting:
        event["onlineMeeting"] = {"joinUrl": join_url}
    return FakeResponse({"value": [event]})


