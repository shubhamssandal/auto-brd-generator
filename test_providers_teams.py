def test_requested_scopes_are_delegated_and_least_privileged(provider):
    url = provider.get_authorization_url("http://localhost:8501", state="s")

    # OnlineMeetingTranscript.Read.All is the narrowest delegated permission Graph
    # offers for reading transcripts; Calendars.Read is what discovery needs.
    assert "OnlineMeetingTranscript.Read.All" in url
    assert "Calendars.Read" in url
    assert "offline_access" in url
    # Application-only permissions must never be requested on a delegated flow.
    assert "OnlineMeetingTranscript.Read.Chat" not in url
    assert ".default" not in url


