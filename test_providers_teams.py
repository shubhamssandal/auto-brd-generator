# --- Meeting resolution ---

def test_meeting_is_resolved_by_join_url_filter(provider, monkeypatch):
    captured = {}

    def fake_get(url, *args, **kwargs):
        captured["url"] = url
        return FakeResponse({"value": [{"id": "meeting-1", "subject": "Refund Dashboard Review"}]})

    monkeypatch.setattr(requests, "get", fake_get)

    meeting = provider.resolve_meeting_by_join_url(JOIN_URL, access_token="at-1")

    assert meeting["id"] == "meeting-1"
    # Graph v1.0 has no list-all endpoint for delegated callers; the JoinWebUrl
    # filter is the supported lookup, and the URL must be encoded in the literal.
    assert "/me/onlineMeetings?$filter=JoinWebUrl%20eq%20'" in captured["url"]
    assert "https%3A%2F%2Fteams.microsoft.com" in captured["url"]


